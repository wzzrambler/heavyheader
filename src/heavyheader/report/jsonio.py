"""Serialisation for scans, baselines and history.

Everything HeavyHeader persists is plain JSON: a baseline file, a history
file, the ``--format json`` output.  No database, no pickle -- the artefacts
are meant to be diffed in a pull request and read by other tools, which rules
out anything clever.

Only the fields that carry meaning are written.  Per-header statistics are
kept in full (they are what trend charts plot) but the raw include-event list
is not (it is large, and can be regenerated by re-running the scan).
"""

from __future__ import annotations

import json
from pathlib import Path

from ..models import (
    CompilerFamily,
    HeaderKind,
    HeaderStats,
    IncludeEvent,
    PhaseTiming,
    ProjectScan,
    RemovalCandidate,
    TranslationUnit,
)

__all__ = ["scan_to_dict", "scan_from_dict", "write_json", "read_json"]

_SCHEMA_VERSION = 1


def _path(value) -> str | None:
    return str(value) if value is not None else None


def scan_to_dict(scan: ProjectScan) -> dict:
    """Serialise a :class:`ProjectScan` to JSON-compatible data."""
    return {
        "schema": _SCHEMA_VERSION,
        "root": str(scan.root),
        "compiler": scan.compiler,
        "compiler_family": scan.compiler_family.value,
        "standard": scan.standard,
        "baseline_seconds": round(scan.baseline_seconds, 6),
        "totals": {
            "translation_units": len(scan.ok_tus),
            "failed_translation_units": len(scan.failed_tus),
            "dependency_edges": scan.total_dependency_edges(),
            "attributed_lines": scan.total_included_lines(),
        },
        "translation_units": [
            {
                "source": str(tu.source),
                "dependencies": [str(p) for p in tu.dependencies],
                "total_seconds": round(tu.total_wall_seconds(), 6),
                "preprocessing_seconds": round(tu.phase_seconds("preprocessing"), 6),
                "parsing_seconds": round(tu.phase_seconds("parsing"), 6),
                "template_instantiation_seconds": round(
                    tu.phase_seconds("template instantiation"), 6
                ),
                "error": tu.error,
            }
            for tu in scan.tus
        ],
        "headers": [
            {
                "path": str(stats.path),
                "kind": stats.kind.value,
                "line_count": stats.line_count,
                "tu_reach": stats.tu_reach,
                "tu_direct": stats.tu_direct,
                "inclusion_events": stats.inclusion_events,
                "max_depth": stats.max_depth,
                "transitive_headers": stats.transitive_headers,
                "transitive_lines": stats.transitive_lines,
                "attributed_lines": stats.attributed_lines,
            }
            for stats in scan.header_stats.values()
        ],
        "candidates": [
            {
                "tu": str(candidate.tu),
                "header": str(candidate.header),
                "line": candidate.line,
                "kind": candidate.kind.value,
                "exclusive_headers": [str(p) for p in candidate.exclusive_headers],
                "estimated_lines_saved": candidate.estimated_lines_saved,
                "estimated_percent": candidate.estimated_percent,
                "measured_seconds_saved": candidate.measured_seconds_saved,
                "verified": candidate.verified,
                "usage_label": candidate.usage_label,
                "confidence": candidate.confidence,
                "notes": list(candidate.notes),
            }
            for candidate in scan.candidates
        ],
        "warnings": list(scan.warnings),
        "template_profile": _template_profile_to_dict(scan),
    }


def _template_profile_to_dict(scan: ProjectScan) -> dict | None:
    """Serialise the template cost profile, if the scanner produced one.

    Per-TU figures are exact (from -ftime-report); the per-header surface is
    a heuristic and is labelled as such in the output.
    """
    profile = getattr(scan, "template_profile", None)
    if profile is None:
        return None
    return {
        "total_seconds": round(profile.total_seconds, 4),
        "overall_percent": round(profile.overall_percent, 2),
        "significant": profile.is_significant,
        "per_tu": [
            {
                "source": str(source),
                "seconds": round(seconds, 4),
                "percent": round(percent, 2),
            }
            for source, seconds, percent in profile.per_tu
        ],
        "heavy_tus": [str(p) for p in profile.heavy_tus],
        "by_surface": [
            {
                "path": str(path),
                "template_declarations": declarations,
                "tu_reach": reach,
                "surface": declarations * reach,
            }
            for path, declarations, reach in profile.by_surface[:20]
        ],
        "note": "per_tu 数字来自 -ftime-report，精确；by_surface 是文本启发式，非实测",
    }


def scan_from_dict(data: dict) -> ProjectScan:
    """Rebuild a :class:`ProjectScan` from :func:`scan_to_dict` output.

    The rebuilt scan is intentionally lossy: include trees and per-phase
    timings are not persisted, so the restored object is suitable for
    *comparison and reporting* but not for re-running attribution.
    """
    family = CompilerFamily(data.get("compiler_family", "gcc"))
    tus: list[TranslationUnit] = []
    for entry in data.get("translation_units", []):
        tus.append(
            TranslationUnit(
                source=Path(entry["source"]),
                dependencies=[Path(p) for p in entry.get("dependencies", [])],
                timings=[
                    PhaseTiming(
                        name="TOTAL", wall_seconds=entry.get("total_seconds", 0.0)
                    )
                ],
                error=entry.get("error"),
            )
        )

    headers = {
        Path(entry["path"]): HeaderStats(
            path=Path(entry["path"]),
            kind=HeaderKind(entry.get("kind", "system")),
            line_count=entry.get("line_count", 0),
            tu_reach=entry.get("tu_reach", 0),
            tu_direct=entry.get("tu_direct", 0),
            inclusion_events=entry.get("inclusion_events", 0),
            max_depth=entry.get("max_depth", 0),
            transitive_headers=entry.get("transitive_headers", 0),
            transitive_lines=entry.get("transitive_lines", 0),
            attributed_lines=entry.get("attributed_lines", 0),
        )
        for entry in data.get("headers", [])
    }

    candidates = [
        RemovalCandidate(
            tu=Path(entry["tu"]),
            header=Path(entry["header"]),
            line=entry.get("line"),
            kind=HeaderKind(entry.get("kind", "system")),
            exclusive_headers=[Path(p) for p in entry.get("exclusive_headers", [])],
            estimated_lines_saved=entry.get("estimated_lines_saved", 0),
            estimated_percent=entry.get("estimated_percent", 0.0),
            measured_seconds_saved=entry.get("measured_seconds_saved"),
            verified=entry.get("verified", False),
            usage_label=entry.get("usage_label", "无法判定"),
            confidence=entry.get("confidence", "unknown"),
            notes=list(entry.get("notes", [])),
        )
        for entry in data.get("candidates", [])
    ]

    scan = ProjectScan(
        root=Path(data.get("root", ".")),
        compiler=data.get("compiler", ""),
        compiler_family=family,
        standard=data.get("standard"),
        tus=tus,
        header_stats=headers,
        candidates=candidates,
        baseline_seconds=data.get("baseline_seconds", 0.0),
        warnings=list(data.get("warnings", [])),
    )
    return scan


def write_json(path: str | Path, payload: dict) -> Path:
    """Write ``payload`` as pretty-printed JSON, creating parent dirs."""
    target = Path(path)
    if target.parent and not target.parent.exists():
        target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(
        json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    return target


def read_json(path: str | Path) -> dict:
    try:
        return json.loads(Path(path).read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise FileNotFoundError(f"{path} does not exist") from exc
    except json.JSONDecodeError as exc:
        raise ValueError(f"{path} is not valid JSON: {exc}") from exc
